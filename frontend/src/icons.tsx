function adapted(Icon:LucideIcon) {
 return forwardRef<SVGSVGElement,LucideProps & {spin?:boolean;rotate?:number}>(({spin,rotate,style,className,...props},ref)=><Icon ref={ref} size={14} {...props} aria-hidden={props['aria-label']?undefined:true} role={props['aria-label']?'img':undefined} className={['ng-icon',spin?'ng-icon-spin':'',className].filter(Boolean).join(' ')} style={{...style,transform:rotate?`rotate(${rotate}deg)`:style?.transform}}/>)
}
